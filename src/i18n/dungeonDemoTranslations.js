/**
 * Helper to get translated dungeon texts based on active language
 */
export function getDungeonText(lang, section, key, vars = {}) {
  const selectedLang = DUNGEON_TRANSLATIONS[lang] ? lang : 'us'
  const textObj = DUNGEON_TRANSLATIONS[selectedLang]?.[section] || DUNGEON_TRANSLATIONS['us'][section] || {}
  let text = textObj[key] || DUNGEON_TRANSLATIONS['us']?.[section]?.[key] || key

  if (typeof text === 'string' && vars && Object.keys(vars).length > 0) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v)
    })
  }
  return text
}
